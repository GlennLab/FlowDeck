/**
 * V2 agent registration — markdown files in the config agents directory.
 *
 * The OpenCode V2 plugin API lets plugins inspect/update/remove agents but
 * not create them (AgentEditor has no add(); see docs/build/plugins/migrate-v1
 * — agents are config-sourced). FlowDeck therefore materializes its twelve
 * agent definitions as `agents/<name>.md` files in the OpenCode config
 * directory, the same mechanism every other agent pack uses.
 *
 * Safety: an existing file is never overwritten unless it carries the
 * FlowDeck marker (user-authored agents with a colliding name win). Writes
 * happen only when content actually changed.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { AgentConfig } from "@opencode-ai/sdk/v2"

export const FLOWDECK_AGENT_MARKER = "<!-- generated by flowdeck -->"

const FRONTMATTER_SCALARS = ["description", "mode", "model", "variant", "color", "hidden", "disable", "temperature", "top_p", "steps", "maxSteps"] as const

function yamlScalar(value: unknown): string | undefined {
  if (typeof value === "string") return /^[\w][\w./-]*$/.test(value) ? value : JSON.stringify(value)
  if (typeof value === "boolean" || typeof value === "number") return String(value)
  return undefined
}

function renderToolsBlock(tools: Record<string, boolean> | undefined): string[] {
  if (!tools || Object.keys(tools).length === 0) return []
  return ["tools:", ...Object.entries(tools).map(([name, enabled]) => `  ${name}: ${enabled}`)]
}

export function renderAgentMarkdown(name: string, config: AgentConfig): string {
  const lines: string[] = ["---"]
  for (const key of FRONTMATTER_SCALARS) {
    const rendered = yamlScalar(config[key])
    if (rendered !== undefined) lines.push(`${key}: ${rendered}`)
  }
  lines.push(...renderToolsBlock(config.tools as Record<string, boolean> | undefined))
  lines.push("---", "", FLOWDECK_AGENT_MARKER, "")
  lines.push(typeof config.prompt === "string" ? config.prompt : `# ${name}`)
  return lines.join("\n") + "\n"
}

export interface AgentFilesResult {
  written: string[]
  skipped: string[]
}

export function ensureAgentFiles(agentsDir: string, configs: Record<string, AgentConfig>): AgentFilesResult {
  const result: AgentFilesResult = { written: [], skipped: [] }
  mkdirSync(agentsDir, { recursive: true })
  for (const [name, config] of Object.entries(configs)) {
    const file = join(agentsDir, `${name}.md`)
    const content = renderAgentMarkdown(name, config)
    if (existsSync(file)) {
      let existing = ""
      try {
        existing = readFileSync(file, "utf-8")
      } catch {
        result.skipped.push(name)
        continue
      }
      if (!existing.includes(FLOWDECK_AGENT_MARKER)) {
        result.skipped.push(name)
        continue
      }
      if (existing === content) continue
    }
    writeFileSync(file, content, "utf-8")
    result.written.push(name)
  }
  return result
}
